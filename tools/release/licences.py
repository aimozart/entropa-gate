"""Third-party licence inventory of the shipped binaries (a stage record (not published)).

licences.py [--roots entropa-gate,entropa-release] [--out THIRD-PARTY-LICENSES.txt]
Reads `cargo metadata --locked --offline --filter-platform x86_64-unknown-linux-gnu`, follows normal and build dependencies from the roots (not dev),
and writes a deterministic list. Exit 1 when a package has no license, or no allowed alternative. The allowlist is deliberately short.
"""
import argparse
import json
import re
import subprocess
import sys

ALLOWED = {"MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Unicode-3.0", "Zlib", "Unlicense", "0BSD", "CC0-1.0"}
EXCEPTIONS = {"LLVM-exception"}


class LicenceError(Exception):
    pass


def _tokens(expr):
    expr = expr.replace("/", " OR ")
    return re.findall(r"\(|\)|[A-Za-z0-9.+\-]+", expr)


def _parse(tokens):
    """Returns the allowed choice of the expression as a sorted tuple of terms, or raises. Grammar: or := and (OR and)*; and := atom (AND atom)*."""
    pos = [0]

    def peek():
        return tokens[pos[0]] if pos[0] < len(tokens) else None

    def take():
        t = peek()
        pos[0] += 1
        return t

    def atom():
        t = take()
        if t is None:
            raise LicenceError("expression ends early")
        if t == "(":
            v = parse_or()
            if take() != ")":
                raise LicenceError("unbalanced parentheses")
            return v
        if t in ("OR", "AND", "WITH", ")"):
            raise LicenceError(f"unexpected {t}")
        name = t
        if peek() == "WITH":
            take()
            exc = take()
            if exc not in EXCEPTIONS:
                raise LicenceError(f"exception not on the list: {exc}")
            name = f"{t} WITH {exc}"
        if t not in ALLOWED:
            return None  # not allowed alternative
        return (name,)

    def parse_and():
        parts = [atom()]
        while peek() == "AND":
            take()
            parts.append(atom())
        if any(p is None for p in parts):
            return None
        return tuple(sorted({x for p in parts for x in p}))

    def parse_or():
        alts = [parse_and()]
        while peek() == "OR":
            take()
            alts.append(parse_and())
        ok = sorted((a for a in alts if a is not None), key=lambda a: (len(a), a))
        return ok[0] if ok else None

    v = parse_or()
    if peek() is not None:
        raise LicenceError("unbalanced parentheses" if peek() == ")" else f"unexpected {peek()}")
    return v


def evaluate(expr):
    """The allowed alternative of an SPDX-style expression, as text (alphabetically first among the allowed ones), or LicenceError."""
    if expr is None or not expr.strip():
        raise LicenceError("no license")
    toks = _tokens(expr)
    if not toks:
        raise LicenceError("no license")
    choice = _parse(toks)
    if choice is None:
        raise LicenceError(f"no allowed alternative in: {expr}")
    return " AND ".join(choice)


def inventory(meta, roots):
    by_id = {p["id"]: p for p in meta["packages"]}
    by_name = {}
    for p in meta["packages"]:
        by_name.setdefault(p["name"], []).append(p["id"])
    edges = {n["id"]: [d["pkg"] for d in n["deps"] if any(k["kind"] in (None, "build") for k in d["dep_kinds"])] for n in meta["resolve"]["nodes"]}
    start = [i for r in roots for i in by_name.get(r, [])]
    if not start:
        raise LicenceError("root package not found: " + ",".join(roots))
    seen, stack = set(), list(start)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        stack.extend(edges.get(i, []))
    ours, third = [], []
    for i in seen:
        p = by_id[i]
        if p.get("source") is None:
            ours.append({"name": p["name"], "version": p["version"], "license": p.get("license")})
            continue
        try:
            chosen = evaluate(p.get("license"))
        except LicenceError as e:
            raise LicenceError(f"{p['name']} {p['version']}: {e}") from None
        third.append({"name": p["name"], "version": p["version"], "license": p["license"], "chosen": chosen})
    key = lambda x: (x["name"], x["version"])
    return {"third_party": sorted(third, key=key), "ours": sorted(ours, key=key)}


def render(inv):
    out = ["THIRD-PARTY LICENCES of the shipped binaries (generated by tools/release/licences.py; one line per package: name version  expression  ->  the allowed alternative)", ""]
    out += [f"{x['name']} {x['version']}  {x['license']}  ->  {x['chosen']}" for x in inv["third_party"]]
    out += ["", "OUR OWN CRATES (workspace; see LICENSE and the crate manifests)", ""]
    out += [f"{x['name']} {x['version']}  {x['license']}" for x in inv["ours"]]
    return "\n".join(out) + "\n"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--roots", default="entropa-gate,entropa-release")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    r = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--offline", "--filter-platform", "x86_64-unknown-linux-gnu"], capture_output=True)
    if r.returncode != 0:
        print("cargo metadata failed", file=sys.stderr)
        return 1
    try:
        text = render(inventory(json.loads(r.stdout), a.roots.split(",")))
    except LicenceError as e:
        print(f"licence check failed: {e}", file=sys.stderr)
        return 1
    if a.out:
        with open(a.out, "x", encoding="utf-8") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
